from copy import deepcopy


def build_scenario_settings(
    *,
    settings: dict,
    market_data: dict,
) -> dict:
    """Assemble runtime configuration from YAML and discovered markets."""
    config = deepcopy(settings)

    # These fields must come from the historical market-data snapshot.
    for key in ("markets", "historical_prices", "start_date"):
        if key in config:
            raise ValueError(f"{key} must be generated by the dataset preparer")

    for key in ("markets", "historical_prices", "start_date"):
        config[key] = deepcopy(market_data[key])

    config.pop("dataset", None)
    return config
